  /* Initialize all configured peripherals */
  MX_GPIO_Init();
  MX_TIM3_Init();
  /* USER CODE BEGIN 2 */
  // 启动PWM输出
  HAL_TIM_PWM_Start(&htim3, TIM_CHANNEL_3);
  uint16_t angle_init = 90;
  __HAL_TIM_SET_COMPARE(&htim3, TIM_CHANNEL_3, angle_init);
  HAL_Delay(2000);
  // 定义测试角度
  uint16_t angles[] = {77, 80, 85, 90, 95, 100, 103};// 角度数组
  int n = sizeof(angles) / sizeof(angles[0]);      // 数组长度
  int index = 0;          // 当前输出位置
  int direction = 1;      // 移动方向：1 向右，-1 向左
  /* USER CODE END 2 */

  /* Infinite loop */
  /* USER CODE BEGIN WHILE */
  while (1)
  {
    __HAL_TIM_SET_COMPARE(&htim3, TIM_CHANNEL_3, angles[index]);
    HAL_Delay(1000);

    // 移动索引
    index += direction;

    // 到达右边界，转向左，跳过右端点（避免重复）
    if (index == n) {
      index = n - 2;   // 回退到倒数第二个元素
      direction = -1;  // 改为向左
    }
    // 到达左边界，转向右，跳过左端点（避免重复）
    else if (index == -1) {
      index = 1;       // 前进到第二个元素
      direction = 1;   // 改为向右
    }
    /* USER CODE END WHILE */

    /* USER CODE BEGIN 3 */
  }
  /* USER CODE END 3 */
